#!/usr/bin/env node
/**
 * scripts/atlas/build-route-feature-map.mjs
 * 
 * Automatically builds the ROUTE_FEATURE_MAP by scanning src/routes.
 */

import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROUTES_DIR = resolve(process.cwd(), 'src/routes');
const OUTPUT_FILE = resolve(process.cwd(), 'src/lib/server/atlas/route-feature-map.ts');

function scanRoutes(dir, currentRoute = '') {
  const entries = [];
  const files = readdirSync(dir);

  for (const file of files) {
    const fullPath = join(dir, file);
    const stat = statSync(fullPath);

    if (stat.isDirectory()) {
      entries.push(...scanRoutes(fullPath, `${currentRoute}/${file}`));
    } else if (file === '+server.ts' || file === '+page.server.ts') {
      entries.push({
        route: currentRoute || '/',
        file: `src/routes${currentRoute}/${file}`,
        type: file.includes('page') ? 'page' : 'api'
      });
    }
  }
  return entries;
}

function main() {
  console.log('🗺️  Atlas: Building Route Feature Map...');
  const routes = scanRoutes(ROUTES_DIR);
  const merged = new Map();

  for (const r of routes) {
    const existing = merged.get(r.route);
    const clusters = [];
    if (r.route.includes('search')) clusters.push('72', '73', '94');
    if (r.route.includes('evidence')) clusters.push('92', '86');
    if (r.route.includes('legal')) clusters.push('47', '35');

    if (!existing) {
      merged.set(r.route, {
        ...r,
        clusters: [...new Set(clusters)],
      });
      continue;
    }

    existing.clusters = [...new Set([...(existing.clusters || []), ...clusters])];
    if (existing.type !== 'page' && r.type === 'page') {
      existing.file = r.file;
      existing.type = r.type;
    }
  }

  const mapEntries = Array.from(merged.values()).map(r => {
    // Heuristic: identify clusters by path
    return `  '${r.route}': {
    route: '${r.route}',
    file: '${r.file}',
    service: 'unknown', // Manual annotation required
    clusters: [${r.clusters.map(c => `'${c}'`).join(', ')}],
    qdrant_collections: ['codebase_chunks_768'],
    redis_keys: [],
    env: []
  }`;
  });

  const content = `/**
 * src/lib/server/atlas/route-feature-map.ts
 * 
 * AUTO-GENERATED by scripts/atlas/build-route-feature-map.mjs
 * Maps SvelteKit routes to topological clusters.
 */

export type RouteFeatureMapEntry = {
  route: string;
  file: string;
  service: string;
  clusters: string[];
  qdrant_collections: string[];
  redis_keys: string[];
  env: string[];
};

export const ROUTE_FEATURE_MAP: Record<string, RouteFeatureMapEntry> = {
${mapEntries.join(',\n')}
};

export function getRouteFeatureMap(route: string): RouteFeatureMapEntry | null {
  return ROUTE_FEATURE_MAP[route] ?? null;
}

export function getRouteClusterPriors(route: string): number[] {
  const entry = getRouteFeatureMap(route);
  if (!entry) return [];
  return entry.clusters.map(id => parseInt(id, 10));
}
`;

  writeFileSync(OUTPUT_FILE, content);
  console.log(`✅ Route Feature Map written to ${OUTPUT_FILE}`);
}

main();
