/**
 * POST /api/reports/police
 * Caller: PoliceReportGenerator.svelte
 * Generates a police incident report using LLM
 */
import { json } from '@sveltejs/kit';
import type { RequestHandler } from './$types';
import { db } from '$lib/server/db/client';
import { reports } from '$lib/server/db/schema';
import { ENV } from '$lib/server/env.server.js';
import { ollamaFetch } from '$lib/server/ollama.js';
import { z } from 'zod';

const policeReportSchema = z.object({
	narrative: z.string().min(1, 'Narrative is required').max(50000),
	evidence: z.array(z.object({ title: z.string().optional(), fileName: z.string().optional(), description: z.string().optional() }).passthrough()).optional().default([]),
	caseId: z.string().max(500).optional(),
});

export const POST: RequestHandler = async ({ request, locals }) => {
	if (!locals.user) {
		return json({ error: 'Unauthorized' }, { status: 401 });
	}

	const parsed = policeReportSchema.safeParse(await request.json());
	if (!parsed.success) {
		return json({ error: parsed.error.issues[0]?.message ?? 'Invalid input' }, { status: 400 });
	}

	const { narrative, evidence, caseId } = parsed.data;

	const evidenceSummary = evidence.length > 0
		? evidence.map((e, i) => `${i + 1}. ${e.title ?? e.fileName ?? 'Item'}: ${e.description ?? 'No description'}`).join('\n')
		: 'No physical evidence listed.';

	const prompt = `You are a police report writing assistant. Generate a formal police incident report in HTML format based on the following narrative and evidence.

## Officer's Narrative
${narrative}

## Evidence Items
${evidenceSummary}

Generate a professional police report with these sections:
1. Incident Summary (date, location, type)
2. Responding Officer Information
3. Narrative of Events
4. Evidence Collected
5. Witness Information (if mentioned)
6. Disposition / Follow-Up Required

Output ONLY HTML content. Use h1, h2, h3, p, ul, li, strong, em tags.`;

	try {
		let html = '';

		// Try LLM generation
		try {
			const res = await ollamaFetch(`${ENV.OLLAMA_BASE_URL}/api/generate`, {
				method: 'POST',
				headers: { 'Content-Type': 'application/json' },
				body: JSON.stringify({
					model: 'gemma4-rotorquant:latest',
					prompt,
					stream: false,
					options: { temperature: 0.3, num_predict: 2048 }
				}),
				signal: AbortSignal.timeout(30000)
			});

			if (res.ok) {
				const data = await res.json();
				const aiHtml = data.response?.trim() ?? '';
				if (aiHtml.length > 100) {
					html = aiHtml;
				}
			}
		} catch {
			// LLM unavailable — use template
		}

		// Template fallback
		if (!html) {
			html = `
<h1>Police Incident Report</h1>
<h2>Incident Summary</h2>
<p><strong>Date:</strong> ${new Date().toLocaleDateString()}</p>
<p><strong>Report Generated By:</strong> AI Assistant (requires officer review)</p>
<h2>Narrative of Events</h2>
<p>${narrative.replace(/\n/g, '</p><p>')}</p>
<h2>Evidence Collected</h2>
${evidence.length > 0
	? `<ul>${evidence.map((e) => `<li><strong>${e.title ?? 'Item'}</strong>: ${e.description ?? 'No description'}</li>`).join('')}</ul>`
	: '<p>No evidence items listed.</p>'}
<h2>Disposition</h2>
<p><em>(AI generation unavailable — complete manually)</em></p>`.trim();
		}

		// Save to DB if caseId provided
		let savedReport: Record<string, unknown> | null = null;
		if (caseId) {
			try {
				const [row] = await db.insert(reports).values({
					caseId,
					title: `Police Report - ${new Date().toLocaleDateString()}`,
					content: html,
					status: 'draft',
					createdBy: Number(locals.user.id),
					metadata: { type: 'police_report' },
				}).returning();
				savedReport = row;
			} catch {
				// DB save non-fatal
			}
		}

		return json({
			success: true,
			report: savedReport ?? { content: html, title: 'Police Incident Report' }
		});
	} catch (err) {
		console.error('[reports/police] Failed:', err);
		return json({ error: 'Failed to generate police report' }, { status: 500 });
	}
};
