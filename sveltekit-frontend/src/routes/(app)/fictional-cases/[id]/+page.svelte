<script lang="ts">
	import Icon from '$lib/components/ui/Icon.svelte';
	import type { PageProps } from './$types';

	let { data }: PageProps = $props();

	let c = $derived(data.caseData);

	function formatCategory(cat: string): string {
		return cat.replace(/_/g, ' ').replace(/\b\w/g, (l) => l.toUpperCase());
	}

	function formatDate(val: string | null | undefined) {
		if (!val) return '—';
		const d = new Date(val);
		if (isNaN(d.getTime())) return val;
		return d.toLocaleDateString(undefined, { year: 'numeric', month: 'long', day: 'numeric' });
	}

	function formatMoney(val: number | null | undefined) {
		if (!val) return '—';
		return new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD', maximumFractionDigits: 0 }).format(val);
	}

	function roleLabel(role: string): string {
		return role.replace(/_/g, ' ').replace(/\b\w/g, (l) => l.toUpperCase());
	}

	function categoryColor(cat: string): string {
		const colors: Record<string, string> = {
			wire_fraud: '#f59e0b', cybercrime: '#8b5cf6', firearms: '#ef4444',
			obstruction: '#f97316', drug_trafficking: '#ec4899', verbal_contracts: '#06b6d4',
			tort_federal: '#10b981', federal_employee_liability: '#6366f1',
		};
		return colors[cat] ?? '#94a3b8';
	}
</script>

