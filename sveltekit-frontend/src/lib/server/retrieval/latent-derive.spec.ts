describe('latent-derive — prefix + L2-renormalize from latent_256', () => {
  it('throws on wrong input dimension', () => {
    expect(() => deriveLatent128(new Float32Array(10))).toThrow('ATLAS_LATENT_256_DIMENSION_MISMATCH');
  });

  it('deriveLatent128 returns a unit-norm 128-dim prefix', () => {
    const latent128 = deriveLatent128(REAL_LATENT_256);
    expect(latent128.length).toBe(LATENT_128_DIM);
    let normSq = 0;
    for (const v of latent128) normSq += v * v;
    expect(Math.sqrt(normSq)).toBeCloseTo(1, 5);
  });

  it('deriveLatent64 matches the real model-produced latent_64 within float32 rounding tolerance', () => {
    const derived64 = deriveLatent64(REAL_LATENT_256);
    expect(derived64.length).toBe(LATENT_64_DIM);
    for (let i = 0; i < LATENT_64_DIM; i++) {
      expect(derived64[i]).toBeCloseTo(REAL_LATENT_64[i], 3);
    }
  });

  it('deriveLatentFamily returns both latent128 and latent64 consistent with individual derive calls', () => {
    const family = deriveLatentFamily(REAL_LATENT_256);
    const soloLatent128 = deriveLatent128(REAL_LATENT_256);
    const soloLatent64 = deriveLatent64(REAL_LATENT_256);
    expect(Array.from(family.latent128)).toEqual(Array.from(soloLatent128));
    expect(Array.from(family.latent64)).toEqual(Array.from(soloLatent64));
  });
});
