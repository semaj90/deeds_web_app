import { z } from 'zod';

/**
 * @typedef {object} ClientValidationResults
 * @description Results from client-side Zod validation for a request payload.
 * @property {boolean} isValid - Overall validity status.
 * @property {Array<{ field: string, error: string }>} errors - List of validation failures.
 */

/**
 * @typedef {object} SchemaMetadata
 * @description Metadata derived from Drizzle/Postgres schema introspection.
 * @property {string} tableName - The name of the table/schema being checked.
 * @property {Array<{ name: string, type: string, isNullable: boolean }>} columns - List of schema columns.
 * @property {Array<{ name: string, constraint: string }>} indexes - List of schema indexes.
 */

/**
 * @typedef {object} DataContractSchema
 * @description The canonical, expected data contract schema for the operation.
 * @property {Array<{ name: string, expectedType: string, required: boolean }>} fields - Expected fields and types.
 * @property {string} contractVersion - Version identifier for the contract.
 */

/**
 * @typedef {object} ContractComplianceReport
 * @description The structured report generated by the merger agent.
 * @property {boolean} schemaDriftStatus - Overall schema drift status.
 * @property {object} schemaDriftDetails - Details of schema drift.
 * @property {boolean} labelComplianceStatus - Overall label compliance status.
 * @property {object.<string, { isCompliant: boolean, details: string }>} labelComplianceDetails - Status per required label.
 * @property {boolean} mergedContractValidityStatus - Overall merged contract validity.
 * @property {string} taskId - The session task ID for context tracking.
 */

/**
 * @fileoverview ContractMergerAgent handles cross-validation of client, server, and contract schemas.
 * @module contract-merger-agent
 */
export class ContractMergerAgent {
    /**
     * @param {string} taskId - The unique ID for the current session context.
     */
    constructor(taskId) {
        this.taskId = taskId;
    }

    /**
     * Compares the client's validation results, the server's schema, and the expected data contract.
     * @param {ClientValidationResults} clientResults
     * @param {SchemaMetadata} serverSchema
     * @param {DataContractSchema} dataContract
     * @returns {Promise<ContractComplianceReport>}
     * @throws {Error} If any required input is missing.
     */
    async verifyContractCompliance(clientResults, serverSchema, dataContract) {
        if (!clientResults || !serverSchema || !dataContract) {
            throw new Error("All three inputs (clientResults, serverSchema, dataContract) are required to run contract verification.");
        }

        const report = {
            schemaDriftStatus: false,
            schemaDriftDetails: {},
            labelComplianceStatus: false,
            labelComplianceDetails: {},
            mergedContractValidityStatus: false,
            taskId: this.taskId,
        };

        // 1. Schema Drift Check (Server Schema vs Data Contract)
        const driftReport = this._checkSchemaDrift(serverSchema, dataContract);
        report.schemaDriftStatus = driftReport.isDriftDetected;
        report.schemaDriftDetails = driftReport.details;

        // 2. Label Compliance Check (Client Results vs Data Contract)
        const labelReport = this._checkLabelCompliance(clientResults, dataContract);
        report.labelComplianceStatus = labelReport.isCompliant;
        report.labelComplianceDetails = labelReport.details;

        // 3. Overall Validity Check
        report.mergedContractValidityStatus = !report.schemaDriftStatus && report.labelComplianceStatus;

        return report;
    }

    /**
     * Compares the server's actual schema (Drizzle/PG) against the expected Data Contract.
     * @private
     * @param {SchemaMetadata} serverSchema
     * @param {DataContractSchema} dataContract
     * @returns {{isDriftDetected: boolean, details: object}}
     */
    _checkSchemaDrift(serverSchema, dataContract) {
        const drift = {
            isDriftDetected: false,
            details: {
                schemaMismatch: {},
                missingFields: [],
                extraServerFields: [],
            }
        };

        // Check for missing fields or type mismatches
        for (const expectedField of dataContract.fields) {
            const schemaField = serverSchema.columns.find(col => col.name === expectedField.name);
            if (!schemaField) {
                drift.details.missingFields.push(expectedField.name);
                drift.details.schemaMismatch[expectedField.name] = {
                    isDrift: true,
                    reason: "Field missing in server schema.",
                    expectedType: expectedField.expectedType
                };
            } else if (schemaField.type !== expectedField.expectedType) {
                drift.details.schemaMismatch[expectedField.name] = {
                    isDrift: true,
                    reason: `Type mismatch: Expected ${expectedField.expectedType}, Found ${schemaField.type}.`,
                    expectedType: expectedField.expectedType
                };
            }
        }

        // Check for extra fields in server schema not defined in the contract
        const contractFieldNames = dataContract.fields.map(f => f.name);
        for (const serverField of serverSchema.columns) {
            if (!contractFieldNames.includes(serverField.name)) {
                drift.details.extraServerFields.push(serverField.name);
            }
        }

        drift.isDriftDetected = drift.details.missingFields.length > 0 || drift.details.extraServerFields.length > 0 || Object.keys(drift.details.schemaMismatch).length > 0;
        return drift;
    }

    /**
     * Compares client validation results against the data contract's required labels.
     * @private
     * @param {ClientValidationResults} clientResults
     * @param {DataContractSchema} dataContract
     * @returns {{isCompliant: boolean, details: object}}
     */
    _checkLabelCompliance(clientResults, dataContract) {
        const compliance = {
            isCompliant: true,
            details: {}
        };
        const requiredLabels = dataContract.fields.filter(f => f.required);

        for (const field of requiredLabels) {
            // In a real scenario, clientResults would contain a structure keyed by field name
            // to check against the contract's 'expectedType'.
            const fieldIsPresent = clientResults.errors.some(err => err.field === field.name); // Placeholder check
            
            const fieldStatus = {
                isCompliant: fieldIsPresent, // Simplified logic
                details: fieldIsPresent ? "Label present and seemingly valid." : "Label missing or failed validation."
            };

            compliance.details[field.name] = fieldStatus;

            if (!fieldStatus.isCompliant) {
                compliance.isCompliant = false;
            }
        }
        return compliance;
    }
}