import fs from 'fs';
import path from 'path';

const reportPath = 'c:/Users/james/Videos/deeds-web-app/sveltekit-frontend/docs_readme/deeds_labs_archive/phase42-ast-report.json';
const vaultPath = process.argv[2];

if (!vaultPath) {
    console.error('Usage: node sync-to-obsidian.js <vaultPath>');
    process.exit(1);
}

if (!fs.existsSync(vaultPath)) {
    fs.mkdirSync(vaultPath, { recursive: true });
}

if (!fs.existsSync(reportPath)) {
    console.error(`Report not found at ${reportPath}`);
    process.exit(1);
}

console.log('\n📓 Chronicler Sync V2: Bridging AST Audit to Obsidian...');

const report = JSON.parse(fs.readFileSync(reportPath, 'utf8'));
const dateStr = new Date().toISOString().split('T')[0];
const timeStr = new Date().toTimeString().split(' ')[0].replace(/:/g, '-');
const filename = path.join(vaultPath, `AST-Audit-${dateStr}-${timeStr}.md`);

let content = `---
title: AST Audit Report ${dateStr}
tags: [audit, ast, agentic, deeds-web-app]
status: deep-audit-complete
timestamp: ${report.timestamp}
files_validated: ${report.summary.validated}
files_failed: ${report.summary.failed}
---

# 🧠 AST-Grounded Research Report - ${dateStr}

## 🔍 Executive Summary
- **Validated Files**: ${report.summary.validated}
- **Failed Repairs**: ${report.summary.failed}
- **Primary Failure**: Svelte 5 Syntax Migration Mismatches

## 🛠️ Critical Bottlenecks (Top 10)
`;

const errors = report.summary.errors.slice(0, 10);

errors.forEach((err) => {
    const fileBasename = path.basename(err.file);
    content += `\n### 📂 ${fileBasename}\n`;
    content += `- **Reason**: ${err.reason}\n`;
    if (err.error) {
        content += `- **Error**: \`${err.error}\` \n`;
    }
    if (err.originalError) {
        content += `- **Root Error**: \`${err.originalError}\` \n`;
    }
});

content += `\n---\n*Generated by Chronicler Sync V2 (AST-Aware)*\n`;

fs.writeFileSync(filename, content, 'utf8');
console.log(`   ✅ Deep Audit Synced: ${filename}`);
console.log('   Done. Obsidian is now grounded in your latest codebase AST.\n');
