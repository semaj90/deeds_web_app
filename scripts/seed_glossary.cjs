const EMBED_MODEL = process.env.EMBED_MODEL || 'embeddinggemma:latest';

/**
 * Fetch a 768-dim embedding from Ollama and return as '[x,y,...]' pgvector literal.
 * Returns null on failure so the row is still inserted (embedding stays NULL).
 */
async function getEmbedding(text) {
  try {
    const resp = await fetch(`${OLLAMA_URL}/api/embed`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ model: EMBED_MODEL, input: [text] }),
      signal: AbortSignal.timeout(15000),
    });
    if (!resp.ok) return null;
    const data = await resp.json();
    const vec = data.embeddings?.[0];
    if (!vec || !vec.length) return null;
    return '[' + vec.join(',') + ']';
  } catch {
    return null;
  }
}

