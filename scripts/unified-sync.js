import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import pg from 'pg';
const { Client } = pg;

/**
 * Unified Sync: Diagnostic -> Cleanup -> Obsidian
 * This script runs the full diagnostic loop and grounds Obsidian in the results.
 */

const projectRoot = 'c:/Users/james/Videos/deeds-web-app';
const frontendDir = path.join(projectRoot, 'sveltekit-frontend');
const vaultPath = process.argv[2] || 'c:/Users/james/Videos/deeds-web-app/scratch/obsidian_vault';

async function run() {
    console.log('🚀 Starting Unified Consolidation Sync...');

    // 1. Run svelte-check
    console.log('🔍 Running diagnostics (svelte-check)...');
    try {
        execSync('npm run check:json', { cwd: frontendDir, stdio: 'pipe' });
    } catch (err) {
        // svelte-check returns exit code 1 if errors found, which is expected
    }

    // 2. Parse the (potentially messy) output
    const rawReportPath = path.join(frontendDir, 'svelte-errors.json');
    if (!fs.existsSync(rawReportPath)) {
        console.error('❌ Error report not found at svelte-errors.json');
        return;
    }

    let rawContent = fs.readFileSync(rawReportPath, 'utf8');
    // Remove terminal noise if present (sometimes svelte-check prepends text)
    const jsonStart = rawContent.indexOf('[');
    const jsonEnd = rawContent.lastIndexOf(']') + 1;
    
    let report = [];
    if (jsonStart !== -1 && jsonEnd !== -1) {
        try {
            report = JSON.parse(rawContent.substring(jsonStart, jsonEnd));
        } catch (e) {
            console.warn('⚠️ JSON parse failed, trying fallback parsing');
            // Basic fallback for non-json output
            report = [];
        }
    }

    // 3. Generate Obsidian Report
    const dateStr = new Date().toISOString().split('T')[0];
    const timeStr = new Date().toTimeString().split(' ')[0].replace(/:/g, '-');
    const filename = path.join(vaultPath, `AST-Audit-${dateStr}-${timeStr}.md`);

    if (!fs.existsSync(vaultPath)) {
        fs.mkdirSync(vaultPath, { recursive: true });
    }

    const errorCount = report.length;
    const uniqueFiles = [...new Set(report.map(r => r.filename))].length;

    let content = `---
title: Production Consolidation Audit ${dateStr}
tags: [audit, ast, svelte5, production]
status: ${errorCount === 0 ? 'clean' : 'remaining-errors'}
error_count: ${errorCount}
files_impacted: ${uniqueFiles}
---

# 🧠 Production Readiness Report - ${dateStr}

## 📊 Summary
- **Total Diagnostics**: ${errorCount}
- **Impacted Files**: ${uniqueFiles}
- **Health Index**: ${errorCount === 0 ? '100% (READY)' : Math.max(0, 100 - errorCount) + '%'}

## 🛠️ Remaining Issues
${errorCount === 0 ? '*No issues detected! Base code is clean.*' : ''}
`;

    // Group by file
    const fileGroups = {};
    report.forEach(err => {
        if (!fileGroups[err.filename]) fileGroups[err.filename] = [];
        fileGroups[err.filename].push(err);
    });

    Object.entries(fileGroups).slice(0, 15).forEach(([file, errors]) => {
        const relPath = path.relative(projectRoot, file);
        content += `\n### 📂 ${path.basename(file)}\n`;
        content += `- **Path**: \`${relPath}\`\n`;
        errors.forEach(e => {
            content += `- [Line ${e.start.line}] **${e.type}**: ${e.message}\n`;
        });
    });

    if (errorCount > 15) {
        content += `\n...and ${errorCount - 15} more diagnostics.\n`;
    }

    content += `\n---\n*Generated by Unified Sync Engine V3*\n`;

    fs.writeFileSync(filename, content, 'utf8');
    console.log(`✅ Obsidian Grounding Complete: ${filename}`);
    console.log(`📊 Status: ${errorCount} errors in ${uniqueFiles} files.`);

    // 4. Log to Metadata Spine (codebase_audit_events)
    console.log('💾 Writing audit event to Metadata Spine...');
    try {
        const dbUrl = process.env.DATABASE_URL || 'postgresql://legal_admin:123456@localhost:5432/legal_ai_db';
        const client = new Client({ connectionString: dbUrl });
        await client.connect();
        await client.query(`
            INSERT INTO codebase_audit_events (audit_type, status, output)
            VALUES ($1, $2, $3)
        `, [
            'unified_sync',
            errorCount === 0 ? 'success' : 'failure',
            JSON.stringify({ errorCount, uniqueFiles, timestamp: new Date().toISOString() })
        ]);
        await client.end();
        console.log('✅ Audit event logged to database.');
    } catch (dbErr) {
        console.error('⚠️ Failed to log audit event to database:', dbErr.message);
    }
}

run().catch(console.error);
