#!/usr/bin/env node

/**
 * Catalog TODO Items from Documentation
 * Searches all markdown files for TODO items and creates a comprehensive catalog
 */

const fs = require('fs');
const path = require('path');
const { glob } = require('glob');

// Configuration
const ROOT_DIR = path.join(__dirname, '..');
const OUTPUT_FILE = path.join(ROOT_DIR, 'PROJECT_ERRORS_TODO.md');

// TODO patterns to search for
const TODO_PATTERNS = [
  /\[ \] (.+)/g,  // [ ] Unchecked items
  /\[TODO\] (.+)/g,  // [TODO] items
  /\[todo\] (.+)/g,  // [todo] items
  /TODO: (.+)/g,  // TODO: items
  /todo: (.+)/g,  // todo: items
  /- \[ \] (.+)/g,  // - [ ] List items
  /\* \[ \] (.+)/g,  // * [ ] List items
];

async function findMarkdownFiles() {
  console.log('🔍 Searching for markdown files...');
  const pattern = '**/*.md';
  const files = await glob(pattern, {
    cwd: ROOT_DIR,
    ignore: ['node_modules/**', '.git/**', 'logs/**']
  });
  return files.map(file => path.join(ROOT_DIR, file));
}

function extractTODOItems(content, filePath) {
  const todos = [];
  const lines = content.split('\n');

  lines.forEach((line, index) => {
    TODO_PATTERNS.forEach(pattern => {
      const matches = line.match(pattern);
      if (matches) {
        matches.forEach(match => {
          // Extract the actual TODO text (remove the pattern prefix)
          const todoText = match.replace(/^\[ \] |\[TODO\] |\[todo\] |TODO: |todo: |- \[ \] |\* \[ \] /, '').trim();
          if (todoText) {
            todos.push({
              text: todoText,
              file: path.relative(ROOT_DIR, filePath),
              line: index + 1,
              raw: line.trim()
            });
          }
        });
      }
    });
  });

  return todos;
}

function categorizeTODOs(todos) {
  const categories = {
    'Redis Validation': [],
    'Error Analysis': [],
    'Production Readiness': [],
    'Performance Optimization': [],
    'System Integration': [],
    'Documentation': [],
    'Future Enhancements': [],
    'Other': []
  };

  todos.forEach(todo => {
    const text = todo.text.toLowerCase();

    if (text.includes('redis') || text.includes('connectivity') || text.includes('persistence')) {
      categories['Redis Validation'].push(todo);
    } else if (text.includes('error') && (text.includes('analysis') || text.includes('scaling') || text.includes('sample'))) {
      categories['Error Analysis'].push(todo);
    } else if (text.includes('production') || text.includes('readiness') || text.includes('metrics')) {
      categories['Production Readiness'].push(todo);
    } else if (text.includes('performance') || text.includes('optimization') || text.includes('gpu') || text.includes('pipeline')) {
      categories['Performance Optimization'].push(todo);
    } else if (text.includes('integration') || text.includes('system') || text.includes('service')) {
      categories['System Integration'].push(todo);
    } else if (text.includes('document') || text.includes('readme') || text.includes('catalog')) {
      categories['Documentation'].push(todo);
    } else if (text.includes('future') || text.includes('enhancement') || text.includes('advanced') || text.includes('blockchain')) {
      categories['Future Enhancements'].push(todo);
    } else {
      categories['Other'].push(todo);
    }
  });

  return categories;
}

function generateMarkdownReport(categories, totalFiles) {
  const timestamp = new Date().toISOString().replace('T', ' ').substring(0, 19);

  let report = `# Project TODO Items - Comprehensive Catalog\n\n`;
  report += `**Generated:** ${timestamp}\n\n`;
  report += `**Files Scanned:** ${totalFiles}\n\n`;
  report += `**Total TODO Items Found:** ${Object.values(categories).reduce((sum, arr) => sum + arr.length, 0)}\n\n`;

  Object.entries(categories).forEach(([category, todos]) => {
    if (todos.length > 0) {
      report += `## ${category} (${todos.length} items)\n\n`;

      todos.forEach(todo => {
        report += `- [ ] ${todo.text}\n`;
        report += `  - *File:* \`${todo.file}:${todo.line}\`\n`;
        report += `  - *Context:* ${todo.raw}\n\n`;
      });
    }
  });

  report += `---\n\n`;
  report += `*Auto-generated by catalog-todo-items.mjs*\n`;
  report += `*Run "Tasks: Run Task" → "📝 Populate PROJECT_ERRORS_TODO.md" to update*\n`;

  return report;
}

async function main() {
  try {
    console.log('🚀 Starting TODO catalog process...');

    // Find all markdown files
    const files = await findMarkdownFiles();
    console.log(`📁 Found ${files.length} markdown files`);

    // Extract TODO items from each file
    const allTodos = [];
    for (const file of files) {
      try {
        const content = fs.readFileSync(file, 'utf8');
        const todos = extractTODOItems(content, file);
        allTodos.push(...todos);
      } catch (error) {
        console.warn(`⚠️ Could not read ${file}: ${error.message}`);
      }
    }

    console.log(`📝 Found ${allTodos.length} TODO items`);

    // Categorize TODOs
    const categories = categorizeTODOs(allTodos);

    // Generate report
    const report = generateMarkdownReport(categories, files.length);

    // Write to file
    fs.writeFileSync(OUTPUT_FILE, report, 'utf8');

    console.log(`✅ TODO catalog written to ${OUTPUT_FILE}`);
    console.log(`📊 Categories: ${Object.keys(categories).filter(cat => categories[cat].length > 0).join(', ')}`);

  } catch (error) {
    console.error('❌ Error during TODO catalog process:', error);
    process.exit(1);
  }
}

if (require.main === module) {
  main();
}

module.exports = { extractTODOItems, categorizeTODOs };
