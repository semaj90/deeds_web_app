#!/usr/bin/env node
/**
 * Phase 79: Validation Test Suite
 *
 * Tests the safety gate to ensure it correctly:
 * - Detects documentation content
 * - Validates code syntax
 * - Prevents file corruption
 */

import fs from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';
import { detectContentType, safeWriteFile, validateFileContent, validatePatchSet } from './phase79-safety-gate.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const testDir = path.join(__dirname, '../.test-phase79');

// Colors for output
const colors = {
  reset: '\x1b[0m',
  green: '\x1b[32m',
  red: '\x1b[31m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  cyan: '\x1b[36m'
};

const log = {
  test: (name) => console.log(`\n${colors.cyan}▶ ${name}${colors.reset}`),
  pass: (msg) => console.log(`${colors.green}✓ ${msg}${colors.reset}`),
  fail: (msg) => console.log(`${colors.red}✗ ${msg}${colors.reset}`),
  info: (msg) => console.log(`${colors.blue}ℹ ${msg}${colors.reset}`),
  warn: (msg) => console.log(`${colors.yellow}⚠ ${msg}${colors.reset}`)
};

// ═══════════════════════════════════════════════════════════════════════════
// TEST CASES
// ═══════════════════════════════════════════════════════════════════════════

const TEST_CASES = [
  {
    name: 'Valid TypeScript code',
    filePath: 'test.ts',
    content: `export interface User {
  id: string;
  name: string;
  email: string;
}

export function createUser(name: string, email: string): User {
  return { id: crypto.randomUUID(), name, email };
}`,
    expectValid: true
  },
  {
    name: 'Documentation content (should be rejected)',
    filePath: 'test.ts',
    content: `The error summary indicates a problem within the __non_route__#internal file.
This file is typically generated by SvelteKit and handles internal logic.
The provided file content is empty, which is highly unusual and suggests corruption.

# No code fix needed. Trigger a full rebuild of the SvelteKit project.`,
    expectValid: false
  },
  {
    name: 'Valid Svelte component',
    filePath: 'test.svelte',
    content: `<script lang="ts">
  import { onMount } from 'svelte';

  let count = 0;

  function increment() {
    count++;
  }

  onMount(() => {
    console.log('Component mounted');
  });
</script>

<button on:click={increment}>
  Count: {count}
</button>

<style>
  button {
    padding: 0.5rem 1rem;
    cursor: pointer;
  }
</style>`,
    expectValid: true
  },
  {
    name: 'Unclosed braces (syntax error)',
    filePath: 'test.ts',
    content: `export function brokenFunction() {
  const x = 42;
  return x;`,
    expectValid: false
  },
  {
    name: 'Valid JavaScript',
    filePath: 'test.js',
    content: `const greeting = (name) => {
  return \`Hello, \${name}!\`;
};

module.exports = { greeting };`,
    expectValid: true
  },
  {
    name: 'Empty file (should be rejected)',
    filePath: 'test.ts',
    content: '',
    expectValid: false
  },
  {
    name: 'Very short content (should be rejected)',
    filePath: 'test.ts',
    content: 'x',
    expectValid: false
  }
];

/**
 * Run all tests
 */
async function runTests() {
  console.log(`\n${colors.cyan}═══ Phase 79: Safety Gate Test Suite ═══${colors.reset}\n`);

  // Setup
  await fs.mkdir(testDir, { recursive: true });

  let passed = 0;
  let failed = 0;

  for (const testCase of TEST_CASES) {
    log.test(testCase.name);

    const validation = validateFileContent(testCase.content, testCase.filePath);
    const isValid = validation.canWrite;

    if (isValid === testCase.expectValid) {
      log.pass(`Validation result: ${isValid ? 'VALID' : 'INVALID'}`);
      passed++;
    } else {
      log.fail(`Expected ${testCase.expectValid ? 'VALID' : 'INVALID'}, got ${isValid ? 'VALID' : 'INVALID'}`);
      if (validation.issues.length > 0) {
        log.info(`Issues: ${validation.issues.join(', ')}`);
      }
      failed++;
    }

    if (validation.issues.length > 0) {
      log.warn(`Issues: ${validation.issues.join(', ')}`);
    }
  }

  // Test content type detection
  console.log(`\n${colors.cyan}▶ Content Type Detection${colors.reset}`);

  const codeContent = `export const test = () => console.log('hi');`;
  const docContent = `The following function is a test. It logs to the console.`;

  const codeDetection = detectContentType(codeContent);
  const docDetection = detectContentType(docContent);

  if (codeDetection.type === 'code') {
    log.pass(`Code detected correctly as '${codeDetection.type}'`);
    passed++;
  } else {
    log.fail(`Code detected as '${codeDetection.type}' (expected 'code')`);
    failed++;
  }

  if (docDetection.type === 'documentation') {
    log.pass(`Documentation detected correctly as '${docDetection.type}'`);
    passed++;
  } else {
    log.fail(`Documentation detected as '${docDetection.type}' (expected 'documentation')`);
    failed++;
  }

  // Test patch set validation
  console.log(`\n${colors.cyan}▶ Batch Patch Validation${colors.reset}`);

  const patches = [
    { filePath: 'valid.ts', content: `const x = 42;` },
    {
      filePath: 'invalid.ts',
      content: `This is documentation. It explains the concept.`
    },
    { filePath: 'valid2.js', content: `function test() { return true; }` }
  ];

  const patchValidation = validatePatchSet(patches);
  log.info(`Valid patches: ${patchValidation.validPatches.length}/${patchValidation.totalPatches}`);
  log.info(`Success rate: ${patchValidation.successRate}%`);

  if (patchValidation.validPatches.length === 2 && patchValidation.invalidPatches.length === 1) {
    log.pass('Batch validation correct');
    passed++;
  } else {
    log.fail('Batch validation incorrect');
    failed++;
  }

  // Test safe file write
  console.log(`\n${colors.cyan}▶ Safe File Write${colors.reset}`);

  const testFilePath = path.join(testDir, 'test.ts');
  const validCode = `export const test = () => 42;`;

  const writeResult = await safeWriteFile(testFilePath, validCode);
  if (writeResult.success) {
    log.pass('File written successfully');
    passed++;
  } else {
    log.fail(`Write failed: ${writeResult.error}`);
    failed++;
  }

  // Test validation blocking
  console.log(`\n${colors.cyan}▶ Validation Blocking${colors.reset}`);

  const badCode = `This is not code. It's documentation that shouldn't be written.`;
  const blockResult = await safeWriteFile(testFilePath, badCode, { validate: true });

  if (!blockResult.success && blockResult.error.includes('Cannot write')) {
    log.pass('Documentation content correctly blocked');
    passed++;
  } else {
    log.fail('Documentation content was not blocked');
    failed++;
  }

  // Cleanup
  await fs.rm(testDir, { recursive: true, force: true });

  // Summary
  console.log(`\n${colors.cyan}═══ Test Summary ═══${colors.reset}`);
  console.log(`${colors.green}✓ Passed: ${passed}${colors.reset}`);
  console.log(`${colors.red}✗ Failed: ${failed}${colors.reset}`);
  console.log(`\nTotal: ${passed + failed} tests\n`);

  process.exit(failed > 0 ? 1 : 0);
}

// Run tests if this is the main module
if (import.meta.url === `file://${process.argv[1]}`) {
  runTests().catch((error) => {
    console.error('Fatal error:', error);
    process.exit(1);
  });
}

export { runTests };
