import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'atlas-actionable-audit-'));
const reports=path.join(root,'docs','reports');fs.mkdirSync(reports,{recursive:true});
const full=[];for(let i=0;i<5;i++)full.push({taskKey:`c:${i}`,change:'c',text:i===0?'live readback remains blocked until authority':'fixture audit proof',state:'OPEN',executionState:'ACTIONABLE',priority:10,dependsOnTaskIds:i===1?['x:1']:[]});
fs.writeFileSync(path.join(reports,'openspec-execution-controller-v1.json'),JSON.stringify({summary:{total:10,proven:4,actionable:5,waiting:1},tasks:full}));
fs.writeFileSync(path.join(reports,'openspec-actionable-work-v1.json'),JSON.stringify({tasks:full.slice(0,2)}));
fs.writeFileSync(path.join(reports,'openspec-blocker-audit-v1.json'),JSON.stringify({groups:[]}));
const script=fileURLToPath(new URL('../scripts/atlas/audit-openspec-actionable-readiness-v2.mjs',import.meta.url));
const run=spawnSync(process.execPath,[script,reports],{encoding:'utf8'});assert.equal(run.status,0,run.stderr);
const r=JSON.parse(fs.readFileSync(path.join(reports,'openspec-actionable-lane-audit-v2.json'),'utf8'));
assert.equal(r.summary.controllerActionable,5);
assert.equal(r.summary.exportedActionableTasks,2);
assert.equal(r.summary.exportTruncationDetected,true);
assert.equal(r.summary.machineDependencyDeclared,1);
assert.ok(r.suspiciousActionable.some(t=>t.taskKey==='c:0'));
